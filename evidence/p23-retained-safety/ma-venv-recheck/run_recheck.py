"""Recheck the exact MA venv entry point; preserve all prior evidence bytes."""
from pathlib import Path
import hashlib
import json
import shutil
import subprocess
import sys
import time
import xml.etree.ElementTree as ET
from collections import Counter

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent
PRIOR = OUT.parent / "public-resume"
FILES = ["tests/test_job_retained_safety_" + name + ".py"
         for name in ("protocol", "owned", "canonical", "public")]


def run(label, interpreter):
    axis = "native" if label == "system" else "venv"
    prior = {p: p.read_bytes() for p in (PRIOR / axis).glob("*.json")}
    junit = "evidence/p23-retained-safety/ma-venv-recheck/" + label + ".xml"
    command = [str(interpreter), "scripts/run_tests_isolated.py", "--", str(interpreter),
               "-m", "pytest", *FILES, "-q", "--tb=short", "--junitxml=" + junit]
    started = time.time()
    print("Starting " + label, flush=True)
    try:
        with (OUT / (label + ".log")).open("wb") as output:
            result = subprocess.run(command, cwd=ROOT, stdout=output, stderr=subprocess.STDOUT)
        artifacts = []
        for path in sorted((PRIOR / axis).glob("*.json")):
            target = OUT / label / path.name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            data = json.loads(target.read_text(encoding="utf-8"))
            artifacts.append({"path": str(target.relative_to(OUT)).replace("\\", "/"),
                              "portReleased": data["portReleased"],
                              "ownedProcessesRemaining": data["ownedProcessesRemaining"]})
        nodes = []
        for case in ET.parse(ROOT / junit).getroot().findall(".//testcase"):
            status = next((s for s in ("failure", "error", "skipped") if case.find(s) is not None), "passed")
            nodes.append({"node": case.attrib["classname"].replace(".", "/") + ".py::" + case.attrib["name"],
                          "status": status})
        record = {"argv": command, "cwd": str(ROOT), "exit": result.returncode,
                  "seconds": round(time.time() - started, 3), "counts": dict(Counter(n["status"] for n in nodes)),
                  "nodes": nodes, "resources": artifacts,
                  "priorEvidence": [{"path": str(p.relative_to(ROOT)).replace("\\", "/"),
                                     "sha256": hashlib.sha256(raw).hexdigest()} for p, raw in prior.items()]}
        (OUT / (label + "-command.json")).write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({"label": label, "exit": result.returncode, "counts": record["counts"]}), flush=True)
        assert result.returncode == 0 and record["counts"] == {"passed": 26}, record["counts"]
        assert all(a["portReleased"] and a["ownedProcessesRemaining"] == [] for a in artifacts)
    finally:
        # Only restore evidence generated by this run, from an exact byte
        # snapshot. Product source and other dirty work are never reset.
        for path, raw in prior.items():
            path.write_bytes(raw)


if __name__ == "__main__":
    run("system", sys.executable)
    run("pan-main-venv", Path("D:/project/Pan-main/.venv/Scripts/python.exe"))
