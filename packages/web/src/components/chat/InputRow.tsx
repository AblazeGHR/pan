function PermissionPill({
  sessionMode,
  defaultMode,
  modes,
  show,
  onApply,
}: {
  sessionMode: string | null;
  defaultMode: string;
  modes: PermissionMode[];
  show: boolean;
  onApply: (key: string, value: string) => void;
}) {
  const [open, setOpen] = useState(false);
  const buttonRef = useRef<HTMLButtonElement>(null);
  const [menuPosition, setMenuPosition] = useState<{ left: number; bottom: number } | null>(null);
  const current = sessionMode || defaultMode;
  const active = modes.find((m) => m.value === current);
  // Keep the collapsed toolbar pill compact; the expanded menu still shows
  // the adapter's full label and its CLI hint.
  const label = (active?.label || current).replace(/\s*\(.*$/, '').trim();

  useEffect(() => {
    if (!open) return;
    const handler = (e: MouseEvent) => {
      const target = e.target as HTMLElement;
      if (!target.closest('[data-perm-pill]') && !target.closest('[data-permission-menu]'))
        setOpen(false);
    };
    document.addEventListener('mousedown', handler);
    return () => document.removeEventListener('mousedown', handler);
  }, [open]);

  useEffect(() => {
    if (!open) {
      setMenuPosition(null);
      return;
    }
    const update = () => {
      const rect = buttonRef.current?.getBoundingClientRect();
      if (rect) setMenuPosition({ left: rect.left, bottom: window.innerHeight - rect.top + 4 });
    };
    update();
    window.addEventListener('resize', update);
    window.addEventListener('scroll', update, true);
    return () => {
      window.removeEventListener('resize', update);
      window.removeEventListener('scroll', update, true);
    };
  }, [open]);

  if (!show) return null;

  return (
    <div data-perm-pill className="relative min-w-0 max-w-full shrink">
      <button
        ref={buttonRef}
        className={PILL_CLASS + ' ' + permBorderClass(current)}
        onClick={() => setOpen(!open)}
      >
        <span className="min-w-0 truncate">{label}</span>
        <ChevronDown size={12} />
      </button>
      {open &&
        menuPosition &&
        createPortal(
          <div
            data-permission-menu
            style={{ position: 'fixed', left: menuPosition.left, bottom: menuPosition.bottom }}
            className="z-[60] mb-1 min-w-[160px] rounded-md border border-border-default bg-bg-primary shadow-lg"
          >
            {modes.map((m) => (
              <div
                key={m.value}
                className={DROPDOWN_ITEM + (m.value === current ? ' bg-accent/10 text-accent' : '')}
                onClick={() => {
                  onApply('permissionMode', m.value);
                  setOpen(false);
                }}
              >
                {m.label}
              </div>
            ))}
          </div>,
          document.body,
        )}
    </div>
  );
}

