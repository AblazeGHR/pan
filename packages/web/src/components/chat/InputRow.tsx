// ── helpers ──

function supportsSetting(
  config: AdapterConfig | null,
  name: string,
): boolean {
  if (!config?.supportedSettings) return false;
  return config.supportedSettings.includes(name);
}

function permBorderClass(value: string): string {
  if (value === 'bypass') return 'border-danger/50';
  if (value === 'yolo' || value === 'acceptEdits') return 'border-warning/50';
  return 'border-border-default';
}

type AttachmentStatus = 'uploading' | 'registering' | 'ready' | 'error';

interface PendingAttachment {
  id: string;
  /** Original/user-facing filename. Never derive the label from path. */
  displayName: string;
  /** Legacy local path used for dedupe/title; not the Markdown label. */
  path?: string;
  /** Safe href generated by the server or the fs download route. */
  href?: string;
  file?: File;
  status: AttachmentStatus;
  loadedBytes?: number;
  totalBytes?: number;
  fileKey?: string;
  error?: string;
  /** Server-owned opaque id used in structured message parts. */
  attachmentId?: string;
  mimeType?: string;
  source?: 'upload' | 'server_file';
}

function attachmentId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`;
}

function clientFileKey(file: File): string {
  return `${file.name}\u0000${file.size}\u0000${file.lastModified}`;
}

function uploadAttachmentIdFromHref(href: string | undefined): string | undefined {
  const match = href?.match(/\/api\/attachments\/(upload_[A-Za-z0-9]{32}(?:\.[A-Za-z0-9._-]{1,32})?)/);
  return match?.[1];
}

